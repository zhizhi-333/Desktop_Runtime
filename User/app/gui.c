/* ---- 画一个字符 ---- */
void GUI_DrawChar(uint16_t x, uint16_t y, char c,
                  uint16_t fg, int16_t bg, uint8_t scale)
{
    const uint8_t *glyph;
    uint8_t col, row;

    if (c < 0x20 || c > 0x7E) c = '?';
    glyph = font5x7[(uint8_t)c - 0x20];

    for (col = 0; col < 5; col++)
    {
        uint8_t bits = glyph[col];
        for (row = 0; row < 7; row++)
        {
            uint16_t px = x + col * scale;
            uint16_t py = y + row * scale;
            if (bits & (1 << row))
            {
                /* 前景像素：填充 scale x scale 方块 */
                LCD_Fill(px, py, px + scale - 1, py + scale - 1, fg);
            }
            else if (bg >= 0)
            {
                /* 背景像素 */
                LCD_Fill(px, py, px + scale - 1, py + scale - 1, (uint16_t)bg);
            }
        }
    }
}

/* ---- 画字符串 ---- */
void GUI_DrawString(uint16_t x, uint16_t y, const char *str,
                    uint16_t fg, int16_t bg, uint8_t scale)
{
    uint16_t cx = x;
    while (*str)
    {
        GUI_DrawChar(cx, y, *str, fg, bg, scale);
        cx += (GUI_FONT_W + 1) * scale;
        str++;
    }
}

/* ---- 画无符号数字 ---- */
void GUI_DrawNum(uint16_t x, uint16_t y, uint32_t num,
                 uint16_t fg, int16_t bg, uint8_t scale)
{
    char buf[11];
    int i = 10;
    buf[10] = '\0';
    if (num == 0) { buf[9] = '0'; GUI_DrawString(x, y, &buf[9], fg, bg, scale); return; }
    while (num > 0 && i > 0)
    {
        buf[--i] = '0' + (num % 10);
        num /= 10;
    }
    GUI_DrawString(x, y, &buf[i], fg, bg, scale);
}

/* ---- 画矩形框(空心) ---- */
void GUI_DrawRect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color)
{
    LCD_Fill(x, y, x + w - 1, y, color);               /* 上边 */
    LCD_Fill(x, y + h - 1, x + w - 1, y + h - 1, color); /* 下边 */
    LCD_Fill(x, y, x, y + h - 1, color);                /* 左边 */
    LCD_Fill(x + w - 1, y, x + w - 1, y + h - 1, color);/* 右边 */
}

/* ---- 画填充按钮 + 居中文字 ---- */
void GUI_DrawButton(uint16_t x, uint16_t y, uint16_t w, uint16_t h,
                    const char *label, uint16_t fg, uint16_t bg, uint8_t scale)
{
    uint16_t text_w, text_h, tx, ty;

    /* 填充按钮背景 */
    LCD_Fill(x, y, x + w - 1, y + h - 1, bg);
    /* 画边框 */
    GUI_DrawRect(x, y, w, h, fg);

    /* 居中显示文字 */
    text_w = GUI_StringWidth(label, scale);
    text_h = GUI_FONT_H * scale;
    tx = x + (w - text_w) / 2;
    ty = y + (h - text_h) / 2;
    GUI_DrawString(tx, ty, label, fg, bg, scale);
}

/* ---- 获取字符串像素宽度 ---- */
uint16_t GUI_StringWidth(const char *str, uint8_t scale)
{
    return (uint16_t)(strlen(str) * (GUI_FONT_W + 1) * scale);
}
